/** Look up a bank by its EFT code (accepts "62", "0062" or the 5-digit IBAN form "00062"). */
export function bankByCode(code: string): string | undefined {
  const n = Number.parseInt(code, 10);
  if (!Number.isFinite(n)) return undefined;
  return BANKS[String(n).padStart(4, "0")];
}
